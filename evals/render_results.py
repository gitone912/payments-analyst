"""
Build the README "Evaluation results" table from saved eval runs, so the numbers are never typed by hand.

    python evals/run_evals.py --paraphrases --save                  # writes evals/results/rules.json
    python evals/run_evals.py --planner llm --paraphrases --save    # writes evals/results/llm.json
    python evals/render_results.py           # rewrites the block between the markers in README.md
    python evals/render_results.py --check   # exit 1 if README.md is out of date (for CI)
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
RESULTS = os.path.join(os.path.dirname(__file__), "results")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- eval-results:start -->", "<!-- eval-results:end -->"
LABEL = {"rules": "Deterministic rules", "llm": "LLM (live)", "auto": "Auto (LLM + fallback)"}


def render() -> str:
    runs = []
    for name in ("rules", "llm", "auto"):
        path = os.path.join(RESULTS, f"{name}.json")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                runs.append(json.load(f))
    if not runs:
        return "_No saved eval runs. Run `python evals/run_evals.py --save`._"
    lines = ["| Planner | Core checks passed | Wrong answers | Provider errors | Held-out paraphrases | Run (UTC) · commit |",
             "|---|---|---|---|---|---|"]
    notes = []
    for r in runs:
        c, p = r["core"], r.get("paraphrases")
        label = LABEL.get(r["planner"], r["planner"])
        if r.get("llm"):
            label += f" `{r['llm']['models'][0]}`"
        para = f"{p['passed']}/{p['total']}" + (f" ({p['provider_errors']} provider errors)" if p and p["provider_errors"] else "") if p else "not run"
        lines.append(f"| {label} | {c['passed']}/{c['total']} | {c['wrong']} | {c['provider_errors']} | {para} "
                     f"| {r['run_at'].replace('T', ' ')[:16]} · `{r['commit'] or 'n/a'}` |")
        if r.get("llm"):
            used = ", ".join(f"`{m}` ×{n}" for m, n in r["llm"]["answered_by"].items()) or "none"
            notes.append(f"- {LABEL.get(r['planner'])}: models tried in order "
                         f"{' → '.join(f'`{m}`' for m in r['llm']['models'])}; answers came from {used}.")
        bad = [x for x in c["cases"] if x["result"] != "PASS"]
        if bad:
            notes.append(f"- {LABEL.get(r['planner'], r['planner'])} not passed: "
                         + "; ".join(f"`{x['id']}` ({x['result']})" for x in bad))
        if p:
            pbad = [x for x in p["cases"] if x["result"] != "PASS"]
            if pbad:
                notes.append(f"- {LABEL.get(r['planner'], r['planner'])} paraphrases not passed: "
                             + "; ".join(f"\"{x['question']}\" ({x['result']})" for x in pbad))
    return "\n".join(lines + ([""] + notes if notes else []))


def main(check: bool) -> int:
    with open(README, encoding="utf-8") as f:
        text = f.read()
    if START not in text or END not in text:
        print(f"README.md has no {START} / {END} markers")
        return 1
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n<!-- generated by evals/render_results.py from evals/results/*.json; do not edit -->\n{render()}\n{END}{tail}"
    if check:
        if new != text:
            print("README.md evaluation results are out of date: run python evals/render_results.py")
            return 1
        return 0
    with open(README, "w", encoding="utf-8") as f:
        f.write(new)
    print("README.md evaluation results updated")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
